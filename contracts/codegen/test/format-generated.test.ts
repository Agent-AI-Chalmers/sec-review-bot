import { mkdtemp, mkdir, rm, writeFile } from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import { expect, test } from 'vitest'

import { formatGenerated } from '../src/format-generated.js'

test('destination configuration controls generated bytes and later config changes take effect', async () => {
  const root = await mkdtemp(path.join(os.tmpdir(), 'generated-format-'))
  try {
    const destination = path.join(root, 'consumer')
    await mkdir(destination)
    await writeFile(path.join(root, '.oxfmtrc.json'), JSON.stringify({ printWidth: 100 }))
    const config = path.join(destination, '.oxfmtrc.json')
    const output = path.join(destination, 'types.ts')
    const source =
      'export type Result = { first: string; second: number; third: boolean; fourth: string }'
    await writeFile(config, JSON.stringify({ printWidth: 40, semi: false }))
    const narrow = await formatGenerated(output, source)
    await writeFile(config, JSON.stringify({ printWidth: 100, semi: false }))
    const wide = await formatGenerated(output, source)
    expect(narrow).not.toBe(wide)
    expect(await formatGenerated(output, wide)).toBe(wide)
  } finally {
    await rm(root, { recursive: true, force: true })
  }
})

test('invalid generated source fails rather than committing partial formatter output', async () => {
  await expect(
    formatGenerated(path.join(import.meta.dirname, 'broken.ts'), 'export type = {')
  ).rejects.toThrow('Failed to format')
})

test('unsupported config overrides fail instead of silently using different formatting', async () => {
  const root = await mkdtemp(path.join(os.tmpdir(), 'generated-overrides-'))
  try {
    await writeFile(
      path.join(root, '.oxfmtrc.json'),
      JSON.stringify({
        overrides: [{ files: ['*.ts'], options: { printWidth: 40 } }]
      })
    )
    await expect(
      formatGenerated(path.join(root, 'types.ts'), 'export type A = string')
    ).rejects.toThrow('Unsupported formatter overrides')
  } finally {
    await rm(root, { recursive: true, force: true })
  }
})
