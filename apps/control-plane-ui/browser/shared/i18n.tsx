type MessageKey = keyof typeof messages.en

export type Message = {
  [K in MessageKey]: Placeholders<(typeof messages.en)[K]> extends never
    ? K
    : never
}[MessageKey]

const LanguageContext = React.createContext<{
  language: Language
  setLanguage: (value: Language) => void
}>({
  language: 'en',
  setLanguage: () => {}
})

export function LanguageProvider({
  children
}: {
  children: React.ReactNode
}): React.JSX.Element {
  // Keep the selected UI language local to this console; it is presentation
  // state, not Review Runs account settings.
  const [language, setLanguage] = React.useState<Language>(
    () =>
      (localStorage.getItem('ui-language') as Language) ||
      (navigator.language.startsWith('zh') ? 'zh' : 'en')
  )
  React.useEffect(() => {
    localStorage.setItem('ui-language', language)
    document.documentElement.lang = language
  }, [language])
  return (
    <LanguageContext.Provider value={{ language, setLanguage }}>
      {children}
    </LanguageContext.Provider>
  )
}

export function useLanguage(): React.ContextType<typeof LanguageContext> {
  return React.useContext(LanguageContext)
}

type Placeholders<S extends string> =
  S extends `${string}{${infer Name}}${infer Rest}`
    ? (Name extends '' ? never : Name) | Placeholders<Rest>
    : never

type MessageArguments<K extends MessageKey> = [
  Placeholders<(typeof messages.en)[K]>
] extends [never]
  ? []
  : [params: Record<Placeholders<(typeof messages.en)[K]>, string | number>]

export type Translator = <K extends MessageKey>(
  key: K,
  ...args: MessageArguments<K>
) => string

export function translate<K extends MessageKey>(
  language: Language,
  key: K,
  ...args: MessageArguments<K>
): string {
  const params = args[0] as Record<string, string | number> | undefined
  // One pass over the template keeps replacement values literal and opaque.
  return messages[language][key].replace(/\{(\w+)\}/g, (token, name: string) =>
    params && Object.hasOwn(params, name) ? String(params[name]) : token
  )
}

export function useMessages(): Translator {
  const { language } = useLanguage()
  return React.useCallback(
    <K extends MessageKey>(key: K, ...args: MessageArguments<K>) =>
      translate(language, key, ...args),
    [language]
  )
}

/** Render a timestamp for the console.
 *
 * `hour12: false` is explicit because the two languages disagree by default: en-US formats with
 * AM/PM and zh-CN without, so the same instant read differently in each console language. An
 * operator comparing a Chinese and an English screen (or a log line) must not have to convert
 * between the two, and 24-hour time is the unambiguous form. The date/time component order still
 * follows the language, which is a genuine locale difference rather than an inconsistency.
 */
export function formatDate(value: string, language: Language): string {
  return new Date(value).toLocaleString(language === 'zh' ? 'zh-CN' : 'en-US', {
    year: 'numeric',
    month: 'numeric',
    day: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit',
    hour12: false
  })
}
